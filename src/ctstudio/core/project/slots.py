"""The 42 original tracks and arenas a custom track can replace (P3-T01, P3-T06).

``slots.json`` beside this file is generated by ``scripts/make_slot_catalogue.py`` from
recorded ``wstrt tracks/arenas --long`` output (Wiimms SZS Tools 2.42a): file name, Wiimm's
English display name and abbreviation, race track or arena, and cup position, in the game's
own order. These are names only (``<file>.szs`` under ``Race/Course``), not game data.
Which slots suit a given track is ``wszst analyze``'s job (TOOLS.md).
"""

from __future__ import annotations

import difflib
import json
from dataclasses import dataclass
from functools import cache
from pathlib import Path
from typing import Any, Literal, cast

CATALOGUE_PATH = Path(__file__).with_name("slots.json")
SlotKind = Literal["race", "arena"]
_KINDS: tuple[SlotKind, ...] = ("race", "arena")
_FIELDS = ("file", "name", "abbr", "kind", "cup", "cup_number", "position")
_COUNTS = {"race": 32, "arena": 10}


class CatalogueError(ValueError):
    """``slots.json`` is damaged; regenerate it with ``scripts/make_slot_catalogue.py``."""


class UnknownSlot(ValueError):
    """No original track or arena has that name."""


@dataclass(frozen=True)
class Slot:
    file: str  # internal name: Race/Course/<file>.szs
    name: str  # English display name, e.g. "Luigi Circuit"
    abbr: str  # Wiimm's abbreviation, e.g. "LC"
    kind: SlotKind
    cup: str  # "Mushroom Cup" ... "Lightning Cup", "Wii Arenas", "Retro Arenas"
    cup_number: int  # 1-based within its kind
    position: int  # 1-based within its cup

    @property
    def label(self) -> str:
        what = "track" if self.kind == "race" else "arena"
        return f"{self.name} ({self.cup}, {what} {self.position})"


def _keys(s: Slot) -> set[str]:
    return {s.file.casefold(), s.name.casefold(), s.abbr.casefold()}


def parse(data: Any) -> tuple[Slot, ...]:
    """Check ``slots.json`` data and return the slots in game order."""
    rows = cast("dict[str, Any]", data).get("slots") if isinstance(data, dict) else None
    if not isinstance(rows, list):
        raise CatalogueError("slots.json must hold a 'slots' list")
    slots = tuple(_slot(i, row) for i, row in enumerate(cast("list[Any]", rows), start=1))
    _check_counts(slots)
    _check_unique(slots)
    return slots


def _check_counts(slots: tuple[Slot, ...]) -> None:
    kinds = [s.kind for s in slots]
    found = {kind: kinds.count(kind) for kind in _KINDS}
    if found != _COUNTS or kinds != sorted(kinds, key=_KINDS.index):
        raise CatalogueError(
            f"slots.json must list 32 race tracks and 10 arenas, in that order; found {found}"
        )


def _check_unique(slots: tuple[Slot, ...]) -> None:
    seen: dict[str, str] = {}
    for s in slots:
        for text in dict.fromkeys((s.file, s.name, s.abbr)):
            key = text.casefold()
            if key in seen:
                raise CatalogueError(f"{text!r} is used twice ({seen[key]} and {s.file})")
            seen[key] = s.file


def _slot(index: int, row: Any) -> Slot:
    if not isinstance(row, dict):
        raise CatalogueError(f"slot {index} must be a table of {', '.join(_FIELDS)}")
    fields = cast("dict[str, Any]", row)
    _check_fields(index, fields)
    for key in ("file", "name", "abbr", "cup"):
        if not _is_text(fields[key]):
            raise CatalogueError(f"slot {index}: {key} must be non-empty text")
    for key in ("cup_number", "position"):
        if not _is_count(fields[key]):
            raise CatalogueError(f"slot {index}: {key} must be a whole number from 1")
    if fields["kind"] not in _KINDS:
        raise CatalogueError(
            f"slot {index}: kind must be 'race' or 'arena', not {fields['kind']!r}"
        )
    return Slot(**fields)


def _check_fields(index: int, fields: dict[str, Any]) -> None:
    missing = [k for k in _FIELDS if k not in fields]
    unknown = sorted(set(fields) - set(_FIELDS))
    problems = [f"missing {', '.join(missing)}"] * bool(missing)
    problems += [f"unknown {', '.join(unknown)}"] * bool(unknown)
    if problems:
        raise CatalogueError(f"slot {index}: {'; '.join(problems)}")


def _is_text(value: Any) -> bool:
    return isinstance(value, str) and bool(value.strip())


def _is_count(value: Any) -> bool:
    return type(value) is int and value >= 1


@cache
def _index() -> dict[str, Slot]:
    return {key: s for s in CATALOGUE for key in _keys(s)}


def find(text: str) -> Slot:
    """The slot named by its file name, display name or abbreviation (any letter case)."""
    index = _index()
    wanted = text.strip().casefold()
    if wanted in index:
        return index[wanted]
    close = difflib.get_close_matches(wanted, list(index), n=3, cutoff=0.75)
    if close:
        names = dict.fromkeys(f"{index[k].file} ({index[k].name})" for k in close)
        hint = f"Did you mean {', '.join(names)}?"
    else:
        hint = (
            "Use a file name, track name or abbreviation (e.g. beginner_course, Luigi Circuit, LC)."
        )
    raise UnknownSlot(f"{text!r} is not an original track or arena. {hint}")


def cups() -> dict[str, tuple[Slot, ...]]:
    """Cup (or arena group) name -> its slots, both in game order (the P5-T02 slot picker)."""
    groups: dict[str, list[Slot]] = {}
    for s in CATALOGUE:
        groups.setdefault(s.cup, []).append(s)
    return {cup: tuple(members) for cup, members in groups.items()}


CATALOGUE: tuple[Slot, ...] = parse(json.loads(CATALOGUE_PATH.read_text(encoding="utf-8")))
SLOTS: tuple[str, ...] = tuple(s.file for s in CATALOGUE)
DEFAULT_SLOT = "beginner_course"
